const fs = require('node:fs');
const path = require('node:path');

const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  withStringsXml,
} = require('expo/config-plugins');

/**
 * «Записати витрату» on a long press of the launcher icon (app-shell, "A long press on the app icon
 * offers «Записати витрату»").
 *
 * One static launcher shortcut: declared in `res/xml/shortcuts.xml` and named by the
 * `android.app.shortcuts` meta-data on the main activity. It fires a `VIEW` intent for
 * `cap1tal://transaction/new` — the scheme's intent filter Expo already generates, and expo-router
 * turns it into the route the «+» on Головний pushes — so there is no JS listener, no native
 * module, no dependency and no permission. The link carries no `type`: the form's own default is a
 * витрата, and an already open form must never be re-read into one (design D9).
 *
 * `android/` is generated by `expo prebuild` and never hand-edited, so all of it is written here.
 * The package and the scheme come from the config, never from this file. The icon's colour is
 * `Colors.light.accent`, copied for the same reason as in `with-android-accent.js`;
 * `src/ui/android-shortcuts.test.ts` fails the moment the two drift apart.
 */
const ACCENT = '#9A6A12';

const SHORTCUT_ID = 'record_expense';
const ICON = 'ic_shortcut_record_expense';
const LABELS = {
  long: { name: 'shortcut_record_expense_long', value: 'Записати витрату' },
  // Launchers show the short label when space is tight; Android asks for ≤ 10 characters.
  short: { name: 'shortcut_record_expense_short', value: 'Витрата' },
};
const META_DATA = 'android.app.shortcuts';

/** `res/xml/shortcuts.xml`: the one shortcut, opening the entry form through the app's scheme. */
function shortcutsXml({ pkg, scheme }) {
  return `<?xml version="1.0" encoding="utf-8"?>
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
  <shortcut
      android:shortcutId="${SHORTCUT_ID}"
      android:enabled="true"
      android:icon="@drawable/${ICON}"
      android:shortcutShortLabel="@string/${LABELS.short.name}"
      android:shortcutLongLabel="@string/${LABELS.long.name}">
    <intent
        android:action="android.intent.action.VIEW"
        android:data="${scheme}://transaction/new"
        android:targetPackage="${pkg}"
        android:targetClass="${pkg}.MainActivity" />
  </shortcut>
</shortcuts>
`;
}

/** `res/drawable/…`: a «+» on a circle in the accent, the same mark as the «+» on Головний. */
function iconXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
  <path
      android:fillColor="${ACCENT}"
      android:pathData="M12,2A10,10 0,1 1,12 22A10,10 0,1 1,12 2Z" />
  <path
      android:fillColor="#FFFFFF"
      android:pathData="M11,7h2v4h4v2h-4v4h-2v-4h-4v-2h4z" />
</vector>
`;
}

/** The manifest with the shortcuts' meta-data on the main activity — once, however often applied. */
function withShortcutsMetaData(manifest) {
  const activity = AndroidConfig.Manifest.getMainActivityOrThrow(manifest);
  const others = (activity['meta-data'] ?? []).filter(
    (item) => item.$['android:name'] !== META_DATA,
  );
  activity['meta-data'] = [
    ...others,
    { $: { 'android:name': META_DATA, 'android:resource': '@xml/shortcuts' } },
  ];
  return manifest;
}

/** `strings.xml` with both labels — shortcut labels must be resources, never literals. */
function assignShortcutStrings(strings) {
  return AndroidConfig.Strings.setStringItem(
    [LABELS.long, LABELS.short].map(({ name, value }) => ({ $: { name }, _: value })),
    strings,
  );
}

function withAndroidShortcuts(config) {
  const pkg = config.android?.package;
  const scheme = Array.isArray(config.scheme) ? config.scheme[0] : config.scheme;
  if (!pkg || !scheme) {
    throw new Error('with-android-shortcuts needs expo.android.package and expo.scheme');
  }
  config = withAndroidManifest(config, (mod) => {
    mod.modResults = withShortcutsMetaData(mod.modResults);
    return mod;
  });
  config = withStringsXml(config, (mod) => {
    mod.modResults = assignShortcutStrings(mod.modResults);
    return mod;
  });
  config = withDangerousMod(config, [
    'android',
    (mod) => {
      const res = path.join(mod.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
      fs.mkdirSync(path.join(res, 'drawable'), { recursive: true });
      fs.writeFileSync(path.join(res, 'xml', 'shortcuts.xml'), shortcutsXml({ pkg, scheme }));
      fs.writeFileSync(path.join(res, 'drawable', `${ICON}.xml`), iconXml());
      return mod;
    },
  ]);
  return config;
}

module.exports = withAndroidShortcuts;
module.exports.ACCENT = ACCENT;
module.exports.LABELS = LABELS;
module.exports.shortcutsXml = shortcutsXml;
module.exports.iconXml = iconXml;
module.exports.withShortcutsMetaData = withShortcutsMetaData;
module.exports.assignShortcutStrings = assignShortcutStrings;
